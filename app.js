function getFamilyForMajor(major) {
  return PROFESSIONAL_TAXONOMY.find(family => family[2].includes(major));
}

function stableMajorNumber(major) {
  return [...major].reduce((sum,char,index) => sum + char.charCodeAt(0) * (index + 3),0);
}

function uniqueItems(items,limit = 8) {
  return [...new Set(items.filter(Boolean).map(item => String(item).trim()).filter(Boolean))].slice(0,limit);
}

function directionTagsFor(name,work,major) {
  const text = `${name}${work}${major}`;
  const rules = [
    [/数据|统计|计量/,"数据分析"],[/算法|智能|模型/,"算法建模"],[/设计|创作|方案/,"方案设计"],[/实验|检验|检测|诊断/,"实验检测"],
    [/法规|合规|标准|审计/,"法规标准"],[/控制|自动化|信号/,"控制系统"],[/生产|工艺|制造/,"生产工艺"],[/研究|科研|理论/,"研究方法"],
    [/管理|运营|项目/,"项目管理"],[/沟通|服务|咨询|传播/,"沟通协作"],[/软件|平台|数字/,"数字工具"],[/临床|医疗|健康/,"专业规范"],
    [/教育|教学|课程/,"教学设计"],[/现场|施工|工程/,"现场实践"]
  ];
  const hits = rules.filter(([pattern]) => pattern.test(text)).map(([,tag]) => tag);
  return uniqueItems([...hits,"专业基础","成果表达","行业理解"],4);
}

function directionReality(name,work,index) {
  const text = `${name}${work}`;
  const onsite = /现场|施工|生产|运维|调试|基地|田野|临床|护理|飞行|航海|训练/.test(text);
  const research = /研究|科研|算法|研发|设计|仿真|诊断/.test(text);
  const publicFacing = /服务|教学|咨询|传播|运营|管理|律师|患者|客户/.test(text);
  const shift = /临床|护理|运行|生产|运维|航海|飞行/.test(text);
  const intensity = Math.min(90,62 + (onsite?10:0) + (research?7:0) + (publicFacing?4:0) + index % 4);
  return {
    intensity,
    environment:onsite ? (research ? "办公室 / 实验室 / 现场" : "现场 / 机构 / 办公室") : (research ? "办公室 / 实验室" : "办公室 / 机构"),
    overtime:shift ? "轮班或事件驱动" : onsite ? "项目节点偏高" : publicFacing ? "业务节点波动" : "阶段性",
    learning:research ? "很高" : "高",
    travel:onsite ? "少量" : "很少",
    stress:intensity >= 78 ? "高" : "中高",
    week:shift ? [62,68,72,70,76,45,35] : onsite ? [52,60,68,72,78,30,18] : [46,54,62,64,72,18,10]
  };
}

