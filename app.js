function refreshFontBaselines(rebuild = false) {
  document.querySelectorAll("[data-font-managed]").forEach(element => {
    element.style.removeProperty("font-size");
    element.removeAttribute("data-font-managed");
  });
  if (rebuild) document.querySelectorAll("[data-font-base]").forEach(element => element.removeAttribute("data-font-base"));
  const records = [...document.querySelectorAll(FONT_TEXT_SELECTOR)].map(element => {
    const moduleName = fontModuleForElement(element);
    if (!moduleName) return null;
    const savedBase = Number.parseFloat(element.dataset.fontBase);
    const baseSize = Number.isFinite(savedBase) ? savedBase : Number.parseFloat(getComputedStyle(element).fontSize);
    return Number.isFinite(baseSize) ? {element,moduleName,baseSize} : null;
  }).filter(Boolean);
  records.forEach(({element,moduleName,baseSize}) => {
    element.dataset.fontBase = String(baseSize);
    element.style.fontSize = `${Math.round(baseSize * fontScales[moduleName] * 100) / 100}px`;
    element.dataset.fontManaged = moduleName;
  });
}

