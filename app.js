function ensureMajorAnalysis(major) {
  const family = getFamilyForMajor(major);
  if (!family) return false;
  if (DATA[major] && PATHWAY_DATA[major]) {
    if (DATA[major].directions.length < 6) {
      const detail = getMajorDetailProfile(major,family);
      const salary = DATA[major].salary || FAMILY_SALARY_BASE[family[0]] || DISCIPLINE_PROFILES[family[3]].salary;
      const supplements = buildGeneratedDirections(major,family,detail,salary)
        .filter(candidate => !DATA[major].directions.some(existing => existing.name === candidate.name));
      DATA[major].directions.push(...supplements.slice(0,6-DATA[major].directions.length));
    }
    const generatedPathway = buildGeneratedPathwayData(major,family);
    PATHWAY_DATA[major].routes.forEach(route => {
      const extra = generatedPathway.routes.find(item => item.name === route.name);
      if (extra) route.notes = uniqueItems([...(route.notes || []),...extra.notes],4);
    });
    return true;
  }
  if (!DATA[major]) DATA[major] = buildGeneratedMajorData(major,family);
  if (!PATHWAY_DATA[major]) PATHWAY_DATA[major] = buildGeneratedPathwayData(major,family);
  GENERATED_MAJOR_NAMES.add(major);
  return true;
}

